/*
 * Photo categories for the Agomoni gallery overlay.
 * Photos are picked from /public/agomoni/glimpses/performances. Some photos
 * appear in more than one category where the set does not have enough
 * distinct shots (inauguration, audience and prize distribution are thin).
 */
export type DriftWallCategory =
  | 'anchor'
  | 'performances'
  | 'inauguration'
  | 'audience'
  | 'prize-distribution';

export interface DriftWallCategoryItem {
  image: string;
  title: string;
  href?: string;
}

export const CATEGORY_LABELS: Record<DriftWallCategory, string> = {
  anchor: 'Anchor',
  performances: 'Performances',
  inauguration: 'Inauguration',
  audience: 'Audience',
  'prize-distribution': 'Prize Distribution',
};

const PHOTO_DIR = '/agomoni/glimpses/performances/';

const toItems = (category: DriftWallCategory, files: string[]): DriftWallCategoryItem[] =>
  files.map((file, i) => ({
    image: PHOTO_DIR + encodeURI(file),
    title: `${CATEGORY_LABELS[category]} ${i + 1}`,
  }));

